/* Help drawer, glossary and guided tour. Static text only (no server data enters this file). */
(function (global) {
  'use strict';
  var $ = function (id) { return document.getElementById(id); };
  var hooks = {switchTab: function () {}};
  var KEY = 'ids_tour_done_v1';

  var GLOSSARY = [
    ['Network connection record (flow)', 'A one-line summary of a connection: who talked to whom, on which port, how many packets and bytes, and for how long. The tool analyses these summaries, not the contents of the traffic.'],
    ['Source and destination', 'The source is the machine that started the connection. The destination is the machine it connected to.'],
    ['Port', 'A numbered door on a computer. Each service listens on its own port, for example 443 for secure web pages and 22 for remote login (SSH).'],
    ['Port scan', 'Trying many ports or many machines to find which services are open. Attackers do this first; administrators also do it with approved tools.'],
    ['Flood (denial of service)', 'Sending so many connections that a server cannot answer real users. A distributed flood comes from many sources at once.'],
    ['Password guessing', 'Many failed logins in a short time. Brute force tries many passwords for one account. Password spraying tries one password against many accounts.'],
    ['Alert', 'Something a detector flagged. Each alert shows why it was flagged, the numbers behind it, and what to check next.'],
    ['Severity', 'How urgent an alert looks: low, medium, high or critical. It is a rule-of-thumb rating based on how far a value is beyond its limit. It is not a probability that an attack is happening.'],
    ['Rule', 'A fixed check such as "20 or more different ports in one minute". Rules are easy to explain but only catch what they describe.'],
    ['Anomaly model', 'A machine-learning model (Isolation Forest) that scores how different each source looks from normal behaviour. It can notice unfamiliar patterns, but unusual does not always mean malicious.'],
    ['Time window', 'The tool looks at each source one minute at a time (five minutes for logins). Very slow attacks can stay under the limits of a window.'],
    ['Threshold', 'The limit that decides when a detector raises an alert. Lower limits give more alerts and more false alarms. You can change them in Settings.'],
    ['False alarm (false positive)', 'Normal activity that was flagged by mistake, for example an approved security scanner.'],
    ['Missed attack (false negative)', 'Malicious activity that was not flagged.'],
    ['Precision', 'Of everything flagged, the share that was really an attack. High precision means few false alarms.'],
    ['Recall', 'Of all real attacks, the share that was caught. High recall means few missed attacks.'],
    ['F1 score', 'One number that balances precision and recall.'],
    ['Accuracy', 'The share of all records classified correctly. It looks good even when attacks are rare, so rely on precision and recall.'],
    ['Synthetic data', 'The included examples were generated by a program with known attacks, so results can be checked. They show how the detectors behave on that data, not how they would perform on a real network.']
  ];

  function helpHtml() {
    return '<div><h3>How to use this page</h3><ol class="help-steps">' +
      '<li><b>Choose data.</b> Click a scenario card at the top. Each is a ready-made example of normal traffic or one kind of attack. To use your own file, select <i>Analyse your own CSV file</i>.</li>' +
      '<li><b>Read the summary.</b> The box under the title says in plain words what was found. The 3D map shows the machines involved.</li>' +
      '<li><b>Open an alert.</b> Click any alert to see why it was flagged, what to check next and the records behind it.</li>' +
      '<li><b>Check accuracy.</b> The <i>Accuracy check</i> tab compares the alerts with the known answers in the example data.</li>' +
      '<li><b>Change sensitivity.</b> In <i>Settings</i>, pick a preset and press <i>Apply and re-run</i>.</li></ol></div>' +
      '<div><h3>What each tab shows</h3><dl class="gloss">' +
      '<div><dt>Summary</dt><dd>Network activity over time, protocols, busiest machines, and whether a server slowed down during an attack.</dd></div>' +
      '<div><dt>Alerts</dt><dd>Every alert in a table. Filter by severity or type, or search for an IP address.</dd></div>' +
      '<div><dt>Unusual behaviour</dt><dd>The anomaly model\'s scores for each machine and minute.</dd></div>' +
      '<div><dt>Accuracy check</dt><dd>How many attacks were caught and how many false alarms there were. Needs a file with an <code>attack_type</code> column.</dd></div>' +
      '<div><dt>Settings</dt><dd>Presets and thresholds that control how easily an alert is raised.</dd></div></dl></div>' +
      '<div><h3>Glossary</h3><dl class="gloss">' + GLOSSARY.map(function (g) { return '<div><dt>' + g[0] + '</dt><dd>' + g[1] + '</dd></div>'; }).join('') + '</dl></div>' +
      '<p class="small muted">This tool reads files. It does not watch a live network, and an alert is a lead for a person to check, not proof of an attack.</p>';
  }
  function openHelp() { $('help-body').innerHTML = helpHtml(); $('help-drawer').hidden = false; $('scrim').hidden = false; $('help-close').focus(); }
  function closeHelp() { $('help-drawer').hidden = true; if ($('drawer').hidden) $('scrim').hidden = true; }

  /* ---------- tour ---------- */
  var STEPS = [
    {sel: '#scenario-cards', title: 'Start with an example', text: 'Each card is a ready-made example: normal traffic, a port scan, a flood, password guessing, or a tricky case. Click one and the analysis runs straight away.'},
    {sel: '#btn-upload-toggle', title: 'Or use your own file', text: 'Select this to analyse your own CSV. You can download an example file there to see the format.'},
    {sel: '#stage', title: 'A 3D map of the machines', text: 'Every dot is a machine in the data. Red dots are sources involved in an alert and amber dots are their targets. Drag to rotate, scroll to zoom, click a dot to list its alerts.'},
    {sel: '#verdict', title: 'The plain-English result', text: 'This box says what was found in everyday words. Click any finding to open its details.', needs: 'results'},
    {sel: '#tiles', title: 'Key numbers', text: 'Alert count, the most serious alert, how many connections were analysed, and whether the file passed the data check. Hover the small "?" icons for explanations.', needs: 'results'},
    {sel: '.tabs', title: 'Go deeper with the tabs', text: 'Summary shows activity over time. Alerts lists everything flagged. Unusual behaviour shows the model\'s scores. Accuracy check compares alerts with the known answers. Settings changes sensitivity.', needs: 'results'},
    {sel: '#btn-help', title: 'Help is always here', text: 'Open Help and glossary any time for a short guide and plain-language definitions of every term.'}
  ];
  var live = [], idx = 0;
  function visible(el) { return !!(el && !el.closest('[hidden]') && window.getComputedStyle(el).display !== 'none'); }
  function place() {
    var st = live[idx], el = document.querySelector(st.sel); if (!el) return;
    el.scrollIntoView({block: 'center', behavior: 'auto'});
    var r = el.getBoundingClientRect(), pad = 6, vw = window.innerWidth, vh = window.innerHeight;
    var top = Math.max(r.top - pad, 4), bottom = Math.min(r.bottom + pad, vh - 4), left = Math.max(r.left - pad, 4), right = Math.min(r.right + pad, vw - 4);
    var hole = $('tour-hole'); hole.style.top = top + 'px'; hole.style.left = left + 'px'; hole.style.width = (right - left) + 'px'; hole.style.height = (bottom - top) + 'px';
    var card = $('tour-card'), ch = card.offsetHeight || 200, cw = card.offsetWidth || 340, y;
    if (bottom + 14 + ch < vh) y = bottom + 14; else if (top - 14 - ch > 0) y = top - 14 - ch; else y = Math.max(12, vh - ch - 12);
    card.style.top = y + 'px'; card.style.left = Math.max(12, Math.min(left, vw - cw - 12)) + 'px';
  }
  function show() {
    var st = live[idx]; $('tour-count').textContent = 'Step ' + (idx + 1) + ' of ' + live.length;
    $('tour-title').textContent = st.title; $('tour-text').textContent = st.text;
    $('tour-back').disabled = idx === 0; $('tour-next').textContent = idx === live.length - 1 ? 'Finish' : 'Next';
    place(); requestAnimationFrame(place);
  }
  function end() { $('tour').hidden = true; try { localStorage.setItem(KEY, '1'); } catch (e) { /* storage may be blocked */ } }
  function startTour() {
    window.scrollTo(0, 0);
    live = STEPS.filter(function (s) { return visible(document.querySelector(s.sel)); });
    if (!live.length) return;
    idx = 0; $('tour').hidden = false; show();
  }
  function seen() { try { return localStorage.getItem(KEY) === '1'; } catch (e) { return true; } }

  function init(h) {
    hooks = h || hooks;
    $('btn-help').addEventListener('click', openHelp); $('help-close').addEventListener('click', closeHelp);
    $('btn-tour').addEventListener('click', startTour);
    $('scrim').addEventListener('click', function () { if (!$('help-drawer').hidden) closeHelp(); });
    $('tour-next').addEventListener('click', function () { if (idx >= live.length - 1) end(); else { idx++; show(); } });
    $('tour-back').addEventListener('click', function () { if (idx > 0) { idx--; show(); } });
    $('tour-skip').addEventListener('click', end);
    window.addEventListener('resize', function () { if (!$('tour').hidden) place(); });
    document.addEventListener('keydown', function (e) {
      if ($('tour').hidden) { if (e.key === 'Escape' && !$('help-drawer').hidden) closeHelp(); return; }
      if (e.key === 'Escape') end(); else if (e.key === 'ArrowRight') $('tour-next').click(); else if (e.key === 'ArrowLeft') $('tour-back').click();
    });
  }
  global.Help = {init: init, openHelp: openHelp, startTour: startTour, tourSeen: seen};
})(window);
